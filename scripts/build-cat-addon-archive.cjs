const { createHash } = require('node:crypto')
const { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } = require('node:fs')
const { join } = require('node:path')
const { deflateRawSync } = require('node:zlib')

const root = join(__dirname, '..')
const packageRoot = join(root, 'assets', 'cat-addon', 'package')
const outputRoot = join(root, 'resources', 'cat-addon')
const archivePath = join(outputRoot, 'cat_addon.zip')
const hashPath = join(outputRoot, 'cat_addon.sha256')
const constantPath = join(root, 'src', 'shared', 'cat-addon-bundle.ts')
const checkOnly = process.argv.includes('--check')

const entryPaths = [
  'animations/animations.json',
  'assets/cat_grey_white.png',
  'manifest.json'
]

const crcTable = new Uint32Array(256)
for (let index = 0; index < crcTable.length; index += 1) {
  let value = index
  for (let bit = 0; bit < 8; bit += 1) value = value & 1 ? 0xedb88320 ^ (value >>> 1) : value >>> 1
  crcTable[index] = value >>> 0
}

function crc32(data) {
  let crc = 0xffffffff
  for (const byte of data) crc = crcTable[(crc ^ byte) & 0xff] ^ (crc >>> 8)
  return (crc ^ 0xffffffff) >>> 0
}

function u16(value) {
  const result = Buffer.alloc(2)
  result.writeUInt16LE(value, 0)
  return result
}

function u32(value) {
  const result = Buffer.alloc(4)
  result.writeUInt32LE(value >>> 0, 0)
  return result
}

function sha256(data) {
  return createHash('sha256').update(data).digest('hex')
}

function validateManifestAssets(entries) {
  const manifest = JSON.parse(entries.find((entry) => entry.path === 'manifest.json').data.toString('utf8'))
  const animations = entries.find((entry) => entry.path === manifest.animations?.path)
  if (!animations) throw new Error('Animation metadata is missing')
  if (animations.data.length !== manifest.animations.size || sha256(animations.data) !== manifest.animations.sha256) {
    throw new Error('Animation metadata integrity is stale')
  }
  for (const asset of manifest.assets ?? []) {
    const entry = entries.find((candidate) => candidate.path === asset.path)
    if (!entry) throw new Error(`Manifest asset is missing: ${asset.path}`)
    if (entry.data.length !== asset.size) throw new Error(`Manifest size is stale for ${asset.path}`)
    if (sha256(entry.data) !== asset.sha256) throw new Error(`Manifest SHA-256 is stale for ${asset.path}`)
  }
  if (!/^\d+\.\d+\.\d+$/.test(manifest.version)) throw new Error('Manifest version is invalid')
  return manifest
}

function createArchive(entries) {
  let localOffset = 0
  const prepared = entries.map((entry) => {
    const compressed = deflateRawSync(entry.data, { level: 9 })
    const result = { ...entry, compressed, crc: crc32(entry.data), localOffset }
    localOffset += 30 + Buffer.byteLength(entry.path) + compressed.length
    return result
  })

  const localRecords = prepared.map((entry) => {
    const name = Buffer.from(entry.path, 'utf8')
    return Buffer.concat([
      u32(0x04034b50), u16(20), u16(0x0800), u16(8), u16(0), u16(33),
      u32(entry.crc), u32(entry.compressed.length), u32(entry.data.length),
      u16(name.length), u16(0), name, entry.compressed
    ])
  })

  const centralOffset = localRecords.reduce((sum, record) => sum + record.length, 0)
  const centralRecords = prepared.map((entry) => {
    const name = Buffer.from(entry.path, 'utf8')
    return Buffer.concat([
      u32(0x02014b50), u16(0x0314), u16(20), u16(0x0800), u16(8), u16(0), u16(33),
      u32(entry.crc), u32(entry.compressed.length), u32(entry.data.length),
      u16(name.length), u16(0), u16(0), u16(0), u16(0), u32(0o100644 << 16),
      u32(entry.localOffset), name
    ])
  })
  const centralSize = centralRecords.reduce((sum, record) => sum + record.length, 0)
  const end = Buffer.concat([
    u32(0x06054b50), u16(0), u16(0), u16(prepared.length), u16(prepared.length),
    u32(centralSize), u32(centralOffset), u16(0)
  ])
  return Buffer.concat([...localRecords, ...centralRecords, end])
}

const entries = entryPaths.map((path) => ({ path, data: readFileSync(join(packageRoot, ...path.split('/'))) }))
const manifest = validateManifestAssets(entries)
const archive = createArchive(entries)
const archiveHash = sha256(archive)
const hashText = `${archiveHash}  cat_addon.zip\n`
const constantText = `// Generated by scripts/build-cat-addon-archive.cjs.\nexport const CAT_ADDON_ARCHIVE_SHA256 = '${archiveHash}'\nexport const CAT_ADDON_BUNDLE_VERSION = '${manifest.version}'\n`

if (checkOnly) {
  const failures = []
  if (!existsSync(archivePath) || !readFileSync(archivePath).equals(archive)) failures.push('cat_addon.zip is stale')
  if (!existsSync(hashPath) || readFileSync(hashPath, 'utf8') !== hashText) failures.push('cat_addon.sha256 is stale')
  if (!existsSync(constantPath) || readFileSync(constantPath, 'utf8') !== constantText) failures.push('cat-addon-bundle.ts is stale')
  if (failures.length > 0) {
    console.error(failures.join('\n'))
    console.error('Run: npm run cat-addon:bundle')
    process.exit(1)
  }
  console.log(`Cat Addon bundle verified (${archive.length} bytes, ${archiveHash}).`)
  process.exit(0)
}

mkdirSync(outputRoot, { recursive: true })
for (const [destination, data] of [[archivePath, archive], [hashPath, hashText], [constantPath, constantText]]) {
  const temporary = `${destination}.${process.pid}.tmp`
  writeFileSync(temporary, data)
  renameSync(temporary, destination)
}
console.log(`Built ${archivePath} (${archive.length} bytes, ${archiveHash}).`)
